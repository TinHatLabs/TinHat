//! The shared actions vectors (contract ACTIONS.md §12.1; byte-equal copies in `testvectors/actions/`, refreshed by
//! `sync-contract.sh`) against the port — the same run as the web's `src/actions/actions.test.ts`: every file, every
//! case, the entry point named by the file's `kind` on the case's `input`, compared with `expect` as canonical JSON
//! (keys in code-point order, numbers like `JSON.stringify`: -0 prints 0). Nothing is skipped or filtered. The text
//! entry point (`call`) must answer the same bytes. Also: the crate's copies equal the contract's files
//! (ACTIONS_CONTRACT_DIR: the contract directory or a tinhat-web tree; skipped when unset or absent), and
//! ACTIONS_EXTRA_VECTORS=<dir> runs more vector files of the same format (e.g. a differential batch generated by the
//! reference), reported on their own.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use serde_json::Value;
use tinhat_actions::{call, dispatch, KINDS};
use tinhat_theme::canon::canon_json;
use tinhat_theme::json::parse_json;

fn crate_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn vec_dir() -> PathBuf {
    crate_dir().join("testvectors").join("actions")
}

/// Every file under `dir`, recursively, sorted per directory (the reference's `files()` order).
fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
    let mut v: Vec<PathBuf> = fs::read_dir(dir).unwrap_or_else(|e| panic!("{}: {e}", dir.display())).map(|e| e.expect("entry").path()).collect();
    v.sort();
    for p in v {
        if p.is_dir() {
            walk(&p, out);
        } else {
            out.push(p);
        }
    }
}

fn json_files(dir: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    walk(dir, &mut out);
    out.retain(|p| p.extension().is_some_and(|e| e == "json"));
    out
}

#[derive(Default)]
struct Run {
    /// kind → (cases, failed)
    counts: BTreeMap<String, (usize, usize)>,
    fails: Vec<String>,
}

impl Run {
    fn total(&self) -> usize {
        self.counts.values().map(|c| c.0).sum()
    }

    fn summary(&self) -> String {
        self.counts.iter().map(|(k, (n, f))| if *f == 0 { format!("{k} {n}") } else { format!("{k} {n} ({f} FAILED)") }).collect::<Vec<_>>().join(", ")
    }
}

fn clip(s: &str) -> String {
    if s.chars().count() > 1200 {
        s.chars().take(1200).collect::<String>() + "…"
    } else {
        s.to_string()
    }
}

/// Run every vector file under `dir`: each case through the typed entry point and through `call` (JSON text).
fn run_dir(dir: &Path) -> Run {
    let mut run = Run::default();
    for f in json_files(dir) {
        let rel = f.strip_prefix(dir).unwrap_or(&f).display().to_string();
        let text = fs::read_to_string(&f).unwrap_or_else(|e| panic!("{rel}: {e}"));
        let doc = parse_json(&text).unwrap_or_else(|e| panic!("{rel}: {e}"));
        let kind = doc.get("kind").and_then(Value::as_str).unwrap_or_else(|| panic!("{rel}: no kind")).to_string();
        let cases = doc.get("cases").and_then(Value::as_array).unwrap_or_else(|| panic!("{rel}: no cases"));
        for c in cases {
            let name = c.get("name").and_then(Value::as_str).unwrap_or("?");
            let input = c.get("input").unwrap_or(&Value::Null);
            let want = canon_json(c.get("expect").unwrap_or(&Value::Null));
            let entry = run.counts.entry(kind.clone()).or_default();
            entry.0 += 1;
            let mut failed = false;
            match dispatch(&kind, input) {
                None => {
                    failed = true;
                    run.fails.push(format!("{rel} — {name}: no entry point {kind}"));
                }
                Some(got) => {
                    let got = canon_json(&got);
                    if got != want {
                        failed = true;
                        run.fails.push(format!("{rel} — {name}\n   input {}\n   got   {}\n   want  {}", clip(&canon_json(input)), clip(&got), clip(&want)));
                    }
                }
            }
            let via_text = call(&kind, &canon_json(input));
            if via_text != want && !failed {
                failed = true;
                run.fails.push(format!("{rel} — {name} (through call)\n   got   {}\n   want  {}", clip(&via_text), clip(&want)));
            }
            if failed {
                entry.1 += 1;
            }
        }
    }
    run
}

fn report(what: &str, run: &Run) {
    eprintln!("{what}: {} cases — {}", run.total(), run.summary());
    for f in run.fails.iter().take(20) {
        eprintln!("DIFF {f}");
    }
    if run.fails.len() > 20 {
        eprintln!("… and {} more", run.fails.len() - 20);
    }
}

#[test]
fn every_vector_reproduces_byte_for_byte() {
    let run = run_dir(&vec_dir());
    report("actions vectors", &run);
    assert!(run.fails.is_empty(), "{} of {} cases differ (first: {})", run.fails.len(), run.total(), run.fails[0]);
    assert!(run.total() > 17000, "only {} cases", run.total());
    for k in KINDS {
        assert!(run.counts.get(k).is_some_and(|c| c.0 > 0), "no {k} vectors");
    }
    for k in run.counts.keys() {
        assert!(KINDS.contains(&k.as_str()), "vectors of an unknown kind {k}");
    }
}

/// More vector files of the same format (ACTIONS_EXTRA_VECTORS=<dir>): e.g. a differential batch the reference
/// generated from random and mutated inputs. Nothing to do when the variable is not set.
#[test]
fn extra_vectors_reproduce() {
    let Ok(dir) = std::env::var("ACTIONS_EXTRA_VECTORS") else { return };
    let run = run_dir(Path::new(&dir));
    report(&format!("extra vectors ({dir})"), &run);
    assert!(run.fails.is_empty(), "{} of {} extra cases differ (first: {})", run.fails.len(), run.total(), run.fails[0]);
    assert!(run.total() > 0, "no cases under {dir}");
}

fn contract_dir() -> PathBuf {
    PathBuf::from(std::env::var("ACTIONS_CONTRACT_DIR").unwrap_or_default())
}

/// Two trees hold the same files with the same bytes.
fn same_tree(a: &Path, b: &Path) -> Result<usize, String> {
    let (mut fa, mut fb) = (Vec::new(), Vec::new());
    walk(a, &mut fa);
    walk(b, &mut fb);
    let ra: Vec<PathBuf> = fa.iter().map(|p| p.strip_prefix(a).unwrap_or(p).to_path_buf()).collect();
    let rb: Vec<PathBuf> = fb.iter().map(|p| p.strip_prefix(b).unwrap_or(p).to_path_buf()).collect();
    if ra != rb {
        let only_a: Vec<String> = ra.iter().filter(|p| !rb.contains(p)).map(|p| p.display().to_string()).take(5).collect();
        let only_b: Vec<String> = rb.iter().filter(|p| !ra.contains(p)).map(|p| p.display().to_string()).take(5).collect();
        return Err(format!("the file lists differ ({} vs {}; only in the contract: {only_a:?}; only in the crate: {only_b:?})", ra.len(), rb.len()));
    }
    for r in &ra {
        if fs::read(a.join(r)).ok() != fs::read(b.join(r)).ok() {
            return Err(format!("{} differs", r.display()));
        }
    }
    Ok(ra.len())
}

/// The crate's copies equal the contract's files byte for byte (sync-contract.sh keeps them so): actions.json,
/// default-rows.json, ACTIONS.md (in the crate exactly when the contract has it) and every vector file. The contract
/// may be the contract directory itself or a tinhat-web tree (src/actions/…).
#[test]
fn copies_equal_the_contract() {
    let c = contract_dir();
    if c.as_os_str().is_empty() {
        eprintln!("SKIPPED: ACTIONS_CONTRACT_DIR is not set (the shared contract directory)");
        return;
    }
    let (base, vectors) = if c.join("actions.json").is_file() && c.join("testvectors/actions").is_dir() {
        (c.clone(), c.join("testvectors/actions"))
    } else if c.join("src/actions/actions.json").is_file() && c.join("src/actions/testvectors/actions").is_dir() {
        (c.join("src/actions"), c.join("src/actions/testvectors/actions"))
    } else {
        eprintln!("SKIPPED: no actions contract at {}", c.display());
        return;
    };
    for f in ["actions.json", "default-rows.json"] {
        let (theirs, mine) = (base.join(f), crate_dir().join(f));
        assert!(fs::read(&theirs).ok() == fs::read(&mine).ok(), "{} differs from the contract's {} (run sync-contract.sh)", mine.display(), theirs.display());
    }
    let (theirs, mine) = (base.join("ACTIONS.md"), crate_dir().join("ACTIONS.md"));
    match (theirs.is_file(), mine.is_file()) {
        (true, true) => assert!(fs::read(&theirs).ok() == fs::read(&mine).ok(), "ACTIONS.md differs from the contract's (run sync-contract.sh)"),
        (true, false) => panic!("the contract has an ACTIONS.md the crate has not copied (run sync-contract.sh)"),
        (false, true) => panic!("the crate holds an ACTIONS.md the contract does not have (run sync-contract.sh)"),
        (false, false) => {}
    }
    let n = same_tree(&vectors, &vec_dir()).unwrap_or_else(|e| panic!("testvectors/actions vs {}: {e} (run sync-contract.sh)", vectors.display()));
    eprintln!("contract copies: actions.json, default-rows.json, ACTIONS.md and {n} vector files identical to {}", c.display());
}
