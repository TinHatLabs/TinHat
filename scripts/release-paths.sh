#!/usr/bin/env bash
# release-paths.sh — write .cargo/release-paths.toml (git-ignored) for THIS machine: it maps the build machine's
# absolute paths to /cargo, /tinhat, /target and /webrtc in Rust panic locations (--remap-path-prefix) and in C/C++
# __FILE__ / debug info (-ffile-prefix-map, through CFLAGS / CXXFLAGS for the cc crate). The binary behaves the same.
# Release use:
#   scripts/release-paths.sh && cargo build --release -p tinhat-app --config .cargo/release-paths.toml
# Don't put these flags in RUSTFLAGS: that variable replaces the repository's own rustflags (.cargo/config.toml).
set -euo pipefail
root=$(cd "$(dirname "$0")/.." && pwd -P)
maps=()
add() {
  [ -n "$1" ] || return 0
  maps+=("$1=$2")
  local p
  p=$(cd "$1" 2>/dev/null && pwd -P) || return 0
  [ "$p" = "$1" ] || maps+=("$p=$2")
}
add "${CARGO_HOME:-$HOME/.cargo}" /cargo          # general first: rustc and GCC apply the LAST matching mapping
add "$root" /tinhat
add "${CARGO_TARGET_DIR:-$root/target}" /target   # may sit inside the checkout, so after it
add "${LK_CUSTOM_WEBRTC:-}" /webrtc
for m in "${maps[@]}"; do
  case $m in *[\"\'\\\ ]*) echo "release-paths: unsupported character in: $m" >&2; exit 1;; esac
done
rf=$(printf "'--remap-path-prefix=%s', " "${maps[@]}")
cf=$(printf ' -ffile-prefix-map=%s' "${maps[@]}")
cat > "$root/.cargo/release-paths.toml" <<TOML
# generated by scripts/release-paths.sh for this machine: never commit
[target.'cfg(all())']
rustflags = [${rf%, }]
[env]
CFLAGS = { value = "${CFLAGS:-}$cf", force = true }
CXXFLAGS = { value = "${CXXFLAGS:-}$cf", force = true }
TOML
echo "wrote .cargo/release-paths.toml (${#maps[@]} mappings)"
