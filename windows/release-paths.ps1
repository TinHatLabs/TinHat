# release-paths.ps1 — write .cargo\release-paths.toml (git-ignored) for THIS machine: maps the cargo home, the checkout,
# the target dir and LK_CUSTOM_WEBRTC to /cargo, /tinhat, /target, /webrtc in Rust panic locations. MSVC has no
# documented prefix map for C/C++ __FILE__: build from a neutral folder with a neutral CARGO_HOME (e.g. C:\tinhat\src
# and C:\cargo) so those paths say nothing about the machine. Use:
#   .\windows\release-paths.ps1; cargo build --release -p tinhat-app --config .cargo\release-paths.toml
# Don't use the RUSTFLAGS variable for this: it replaces the repository's rustflags (crt-static, the delay-loaded
# NVIDIA DLLs) and the link fails or the exe won't start without an NVIDIA driver.
$ErrorActionPreference = "Stop"
$root   = (Resolve-Path "$PSScriptRoot\..").Path
$cargo  = if ($env:CARGO_HOME) { $env:CARGO_HOME } else { Join-Path $env:USERPROFILE ".cargo" }
$target = if ($env:CARGO_TARGET_DIR) { $env:CARGO_TARGET_DIR } else { Join-Path $root "target" }
$maps = @("$cargo=/cargo", "$root=/tinhat", "$target=/target")      # general -> specific (the last match wins)
if ($env:LK_CUSTOM_WEBRTC) { $maps += "$($env:LK_CUSTOM_WEBRTC)=/webrtc" }
if ($maps -match "'") { throw "a path contains an apostrophe" }
$rf = ($maps | ForEach-Object { "'--remap-path-prefix=$_'" }) -join ", "
@("# generated by windows/release-paths.ps1 for this machine: never commit", "[target.'cfg(all())']", "rustflags = [$rf]") |
  Set-Content -Encoding ascii (Join-Path $root ".cargo\release-paths.toml")
Write-Host "wrote .cargo\release-paths.toml ($($maps.Count) mappings)"
